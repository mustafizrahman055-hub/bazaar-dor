// Simple string hashing function to use as a daily seed
const hashString = (str) => {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash = hash & hash;
  }
  return Math.abs(hash);
};

// Simulate daily accurate market prices based on a seed
function simulateDailyPrices(products) {
  const dateSeed = new Date().toISOString().split('T')[0]; 
  
  return products.map(product => {
    // Generate a unique seed for each product for today
    const seed = hashString(`${product.slug}-${dateSeed}`);
    
    // Simulate a random fluctuation between -3% to +3%
    const fluctuationPercent = ((seed % 7) - 3); 
    const basePrice = product.today; // Use the provided 'today' as the baseline
    
    // Calculate new today price
    let newToday = Math.round(basePrice * (1 + fluctuationPercent / 100));
    let newYesterday = product.today; // the baseline was yesterday's
    
    // Determine change
    let dir = "flat";
    if (newToday > newYesterday) dir = "up";
    else if (newToday < newYesterday) dir = "down";
    
    const pct = newYesterday === 0 ? 0 : Number((Math.abs(newToday - newYesterday) / newYesterday * 100).toFixed(1));

    // Also slightly adjust market min/max if they exist
    const newMarkets = product.markets?.map(m => ({
      ...m,
      min: Math.max(1, Math.round(m.min * (1 + fluctuationPercent / 100))),
      max: Math.round(m.max * (1 + (fluctuationPercent + (seed % 3)) / 100))
    })) || [];

    return {
      ...product,
      today: newToday,
      yesterday: newYesterday,
      change: { dir, pct },
      markets: newMarkets
    };
  });
}

